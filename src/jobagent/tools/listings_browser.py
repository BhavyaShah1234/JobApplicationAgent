"""Read public Workday listings through the site's normal Chrome interface.

Only observe responses generated by navigation and the visible Next button.
Keep supplied filters, stop on a browser-side refusal, and hand visible security
challenges to the normal human channel. No identity masking or CAPTCHA solving.
"""

import re
from urllib.parse import parse_qsl, urlencode, urlparse, urlunparse

from jobagent.tools import listings as L


def _board(careers):
    board = careers.get('board') or L.board_of(careers.get('url', ''))
    if not board or board['family'] != 'workday':
        raise ValueError('A public Workday careers board is required')
    match = re.fullmatch(r'([a-zA-Z0-9-]+)/(wd\d+)/([a-zA-Z0-9_-]+)', board['token'])
    if not match:
        raise ValueError('Invalid Workday board identity')
    tenant, wd, site = match.groups()
    host = tenant + '.' + wd + '.myworkdayjobs.com'
    supplied = careers.get('url', '')
    parsed = urlparse(supplied)
    supplied_board = L.board_of(supplied)
    if (parsed.scheme == 'https' and parsed.netloc == host and supplied_board
            and supplied_board['token'] == board['token']):
        # Search discovery may have found one specific posting. Collection must
        # open its board, including the caller's filters, not that stale posting.
        base = urlunparse(parsed._replace(path=parsed.path.split('/job/', 1)[0], fragment=''))
    else:
        base = 'https://' + host + '/en-US/' + site
    return tenant, host, site, base


def _request_matches(response, endpoint, query, facets, offset):
    if response.url.split('?')[0] != endpoint or response.request.method != 'POST':
        return False
    try:
        body = response.request.post_data_json
        applied = body.get('appliedFacets') or {}
        return (body.get('searchText', '') == query and body.get('offset', 0) == offset
                and all(set(applied.get(k, [])) == set(v) for k, v in facets.items()))
    except (TypeError, ValueError, AttributeError):
        return False


def _decode(response):
    if response.status in (401, 403, 429) or response.status >= 500:
        raise L.Blocked('Workday public browser listing answered ' + str(response.status))
    if response.status != 200:
        raise L.Blocked('Workday public browser listing unavailable (' + str(response.status) + ')')
    data = response.json()
    if not isinstance(data, dict) or not isinstance(data.get('jobPostings'), list):
        raise L.Blocked('Workday did not return a public listing page')
    return data


def _navigate_json(page, url, matches, controller):
    from playwright.sync_api import TimeoutError as PlaywrightTimeout
    from jobagent.tools import challenge

    for attempt in range(3):
        try:
            with page.expect_response(matches, timeout=20000) as pending:
                response = page.goto(url, wait_until='domcontentloaded', timeout=45000)
                block = challenge.detect(page)
                if block and block.kind != 'unknown':
                    raise PlaywrightTimeout('Visible human verification')
                if response and response.status >= 400:
                    raise L.Blocked('Workday careers page answered ' + str(response.status))
            return pending.value
        except PlaywrightTimeout as exc:
            block = challenge.detect(page)
            if not block or block.kind == 'unknown':
                raise L.Blocked('No Workday response matching the requested page and filters') from exc
            try:
                controller.wait(page, block)
            except challenge.Blocked as stopped:
                raise L.Blocked(str(stopped)) from stopped
    raise L.Blocked('Workday human verification did not resolve')


def read_workday_detail(url, *, context_factory=None, log=print):
    """Observe the public detail response for this exact posting, not another role."""
    from jobagent.tools import challenge
    from jobagent.tools.browser import persistent_context
    from jobagent.tools.hitl import open_hitl

    tenant, host, site, _ = _board({'url': url})
    parsed = urlparse(url)
    if '/job/' not in parsed.path:
        raise ValueError('A Workday posting URL is required')
    path = parsed.path[parsed.path.index('/job/'):]
    endpoint = 'https://' + host + '/wday/cxs/' + tenant + '/' + site + path
    with (context_factory or persistent_context)() as ctx:
        page = ctx.pages[0]
        controller = challenge.Controller(open_hitl(log), log=log)
        response = _navigate_json(page, url, lambda r: r.url.split('?')[0] == endpoint and r.request.method == 'GET', controller)
        if response.status != 200:
            raise L.Blocked('Workday public posting detail answered ' + str(response.status))
        data = response.json()
        if not isinstance(data, dict) or not isinstance(data.get('jobPostingInfo'), dict):
            raise L.Blocked('Workday returned no public posting detail')
        return data


def collect_workday(careers, company, queries=None, log=print, *, context_factory=None):
    from playwright.sync_api import TimeoutError as PlaywrightTimeout
    from jobagent.tools import challenge
    from jobagent.tools.browser import persistent_context
    from jobagent.tools.hitl import open_hitl

    tenant, host, site, base = _board(careers)
    searches, facets = L.workday_searches(base, queries)
    endpoint = 'https://' + host + '/wday/cxs/' + tenant + '/' + site + '/jobs'
    found, seen = [], set()
    with (context_factory or persistent_context)() as ctx:
        page = ctx.pages[0]
        controller = challenge.Controller(open_hitl(log), log=log)
        for query in searches:
            parsed = urlparse(base)
            pairs = [(k, v) for k, v in parse_qsl(parsed.query, keep_blank_values=True) if k != 'q']
            if query:
                pairs.append(('q', query))
            url = urlunparse(parsed._replace(query=urlencode(pairs)))
            response = _navigate_json(page, url, lambda r: _request_matches(r, endpoint, query, facets, 0), controller)
            data = _decode(response)
            # Some boards report the remaining count after the requested offset.
            # Keep the initial count; comparing an absolute offset with a later
            # remaining count would stop early (e.g. 40 >= 39 for 59 jobs).
            total = data.get('total')
            for page_number in range(L.WORKDAY_PAGES):
                rows = L.parse_workday(data, company, host, site)
                for item in rows:
                    if item.url not in seen:
                        seen.add(item.url)
                        found.append(item)
                log(f'listings: {company}: Chrome search {query!r}, page {page_number + 1}: {len(rows)} listings')
                if len(rows) < 20 or isinstance(total, int) and (page_number + 1) * 20 >= total:
                    break
                if page_number + 1 == L.WORKDAY_PAGES:
                    log(f'listings: {company}: browser page budget reached; additional matches were not read')
                    break
                # Dismiss only the normal optional-cookie choice, never a security control.
                decline = page.get_by_role('button', name=re.compile(r'^decline(?: optional cookies)?$', re.I))
                if decline.count() == 1 and decline.is_visible():
                    decline.click()
                next_page = page.get_by_role('button', name=re.compile(r'^next(?: page)?$', re.I))
                if next_page.count() != 1 or not next_page.is_enabled():
                    log(f'listings: {company}: more results exist but no usable Next control was found; collection is partial')
                    break
                try:
                    with page.expect_response(lambda r: _request_matches(r, endpoint, query, facets, (page_number + 1) * 20), timeout=20000) as pending:
                        next_page.click(timeout=10000)
                    data = _decode(pending.value)
                except PlaywrightTimeout as exc:
                    raise L.Blocked('Workday pagination did not return the requested filtered page') from exc
                page.wait_for_timeout(int(L.PAUSE_S * 1000))
    return found
